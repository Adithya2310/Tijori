import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { emptyVault, applyAction, publicState, validateVault } from '../lib/vault.ts';
import { generateIdentity, unlockIdentity } from '../lib/identity-key.ts';
const addr = (n: number) => '0x' + n.toString(16).padStart(40, '0');
const keyEnvelope = { version: 1, salt: 'aa'.repeat(16), iv: 'bb'.repeat(12), ciphertext: 'cc'.repeat(48) };
import { encryptState, decryptState } from '../lib/arkiv/codec.ts';
test('encrypted state uses fresh IVs, binds context, rejects tampering/wrong keys and oversized state', () => {
 const vault = emptyVault(), key = randomBytes(32), context = 'testnet:owner:namespace:1';
 applyAction(vault, 'signup', { name: 'Alice', address: addr(1), keyEnvelope, objectName: 'Blue mug' });
 const a = encryptState(vault, key, context), b = encryptState(vault, key, context);
 assert.notDeepEqual(a, b); assert.deepEqual(decryptState(a, key, context), vault);
 assert.ok(!a.includes(Buffer.from('Blue mug')));
 assert.throws(() => decryptState(a, randomBytes(32), context));
 assert.throws(() => decryptState(a, key, 'other-namespace'));
 const corrupt = Buffer.from(a); corrupt[30] ^= 1; assert.throws(() => decryptState(corrupt, key, context));
 const big = emptyVault(); for (let i = 0; i < 20; i++) applyAction(big, 'signup', { name: `P${i}`, address: addr(i+10), keyEnvelope, objectName: 'x'.repeat(8000) });
 assert.throws(() => encryptState(big, key, context), /storage limit/);
});
test('invitation claims preserve membership and private fields stay outside public state', () => {
 const vault = emptyVault();
 const a = applyAction(vault, 'signup', { name: 'Alice', address: addr(1), keyEnvelope, objectName: 'mug' });
 applyAction(vault, 'groups', { name: 'Pair', creatorId: a, addresses: [addr(2), addr(2), addr(1)] });
 const invited = vault.groups[0].memberIds[1];
 assert.equal(applyAction(vault, 'signup', { name: 'Bob', address: addr(2), keyEnvelope, objectName: 'book' }), invited);
 applyAction(vault, 'transactions', { groupId: vault.groups[0].id, senderId: a, recipient: 'demo', asset: 'ETH', amount: 1 });
 assert.equal(vault.transactions[0].status, 'pending');
 applyAction(vault, 'approve', { transactionId: vault.transactions[0].id, walletId: invited });
 assert.equal(vault.transactions[0].status, 'completed'); validateVault(vault);
 const state = JSON.stringify(publicState(vault)); assert.ok(!state.includes('object_name')); assert.ok(!state.includes('frequency'));
 const bad = structuredClone(vault); bad.groups[0].memberIds.push('missing'); assert.throws(() => validateVault(bad));
});

test('migrates legacy state and binds a verified Safe to its signer identities', async () => {
 const { normalizeOwners, validateSalt, verifySafeDeployment } = await import('../lib/safe.ts');
 const legacy = { version: 1, wallets: [], groups: [], transactions: [], operations: [] };
 const vault = validateVault(legacy);
 assert.equal(vault.version, 4);
 assert.deepEqual([vault.proposals, vault.invoices], [[], []]);
 const creator = applyAction(vault, 'signup', { name: 'Creator', address: addr(9), keyEnvelope, objectName: 'demo' });
 const owners = normalizeOwners(['0x1111111111111111111111111111111111111111', '0x2222222222222222222222222222222222222222', '0x3333333333333333333333333333333333333333']);
 const safe = { chainId: 84532 as const, address: '0x4444444444444444444444444444444444444444' as const, owners, threshold: 2, deploymentTxHash: `0x${'aa'.repeat(32)}` as `0x${string}`, saltNonce: '10' };
 applyAction(vault, 'register-safe', { name: 'Real Safe', creatorId: creator, safe });
 assert.equal(validateVault(vault).groups[0].safe?.address, safe.address);
 const view = publicState(vault).groups[0];
 assert.equal(view.safe?.threshold, 2);
 assert.equal(view.members.length, 3);
 assert.equal(view.members[0].id, creator);
 assert.equal(view.members[1].address, owners[1].toLowerCase());
 assert.throws(() => applyAction(vault, 'register-safe', { name: 'Duplicate', creatorId: creator, safe }), /already registered/);
 assert.throws(() => applyAction(vault, 'transactions', { groupId: view.id, senderId: creator, recipient: 'demo', asset: 'ETH', amount: 1 }), /Use Safe/);
 const broken = structuredClone(vault); broken.groups[0].safe!.threshold = 1;
 assert.throws(() => validateVault(broken), /Invalid group/);
 assert.throws(() => normalizeOwners([owners[0], owners[0]]), /unique/);
 assert.throws(() => normalizeOwners([owners[0], 'not an address']), /valid wallet/);
 assert.throws(() => validateSalt('-1'), /salt/);
 await assert.rejects(verifySafeDeployment({ owners, saltNonce: '1', address: 'not-an-address', deploymentTxHash: 'bad' }), /Invalid Safe address/);
});

test('generated keys are passphrase encrypted and bound to their address', async () => {
 const { address, keyEnvelope: envelope } = await generateIdentity('a strong test passphrase');
 await unlockIdentity(address, envelope, 'a strong test passphrase');
 await assert.rejects(unlockIdentity(address, envelope, 'wrong passphrase'));
 await assert.rejects(unlockIdentity(addr(99), envelope, 'a strong test passphrase'));
 const vault = emptyVault(); applyAction(vault, 'signup', { name: 'A', address, keyEnvelope: envelope, objectName: 'mug' });
 assert.ok(!JSON.stringify(publicState(vault)).includes(envelope.ciphertext));
 const legacy = validateVault({ version: 2, wallets: [{id:'x', name:'Old', world_id:'old-id', object_name:'mug', created_at:'now'}], groups: [], transactions: [], operations: [] });
 assert.equal(legacy.wallets[0].address, null); assert.equal(legacy.wallets[0].legacy_id, 'old-id');
});
